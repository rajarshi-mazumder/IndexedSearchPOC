import { test, expect } from "@playwright/test";
test("settings, progressive fetch, embedding and ranked search work through real workers", async ({ page }, testInfo) => {
  const errors: string[] = []; page.on("pageerror", (error) => errors.push(error.message));
  page.on("console", (message) => { if (message.type() === "error") errors.push(message.text()); });
  await page.goto("/");
  await expect(page.getByRole("heading", { name: "Fetch candidates", exact: true })).toBeVisible();
  await expect(page.locator(".sidebar")).toHaveCSS("position", "fixed");
  await page.getByRole("button", { name: "Configuration", exact: true }).click();
  await page.getByRole("textbox", { name: "Configuration name" }).fill("Full sandbox test");
  await page.getByRole("button", { name: "Save configuration" }).click();
  await expect(page.getByRole("status")).toContainText("Configuration saved");
  await expect(page.getByRole("button", { name: "Save configuration", exact: true })).toBeEnabled();
  await page.screenshot({ path: testInfo.outputPath("configuration.png"), fullPage: true });
  await page.getByRole("button", { name: "Fetch candidates", exact: true }).click();
  await page.getByRole("button", { name: "Fetch new dataset" }).click();
  await expect(page.locator("operation-progress .status")).toHaveText("succeeded");
  await expect(page.getByText("1,000 records across 1 files.", { exact: false })).toBeVisible();
  await page.getByRole("button", { name: "Resume fetch" }).click();
  await expect(page.getByText("1,005 records across 2 files.", { exact: false })).toBeVisible();
  await page.locator(".batch-library tbody tr").first().getByRole("button", { name: "Preview" }).click();
  await expect(page.getByText("Maya Chen 1", { exact: true })).toBeVisible();
  await page.locator(".preview-card").getByRole("button", { name: "Next →" }).click();
  await expect(page.getByText("Maya Chen 21", { exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("fetch-preview.png"), fullPage: true });
  await page.getByRole("button", { name: "Embed & index", exact: true }).click();
  await page.getByRole("textbox", { name: "Destination index" }).fill("candidates-fsb-test");
  await page.getByRole("button", { name: "Set up index", exact: true }).click();
  await expect(page.getByText("Registered model:", { exact: false })).toBeVisible();
  await page.getByRole("checkbox", { name: "Select this page" }).check();
  await page.getByRole("button", { name: "Embed 2 selected file(s)", exact: true }).click();
  await page.getByRole("button", { name: "Activity", exact: false }).click();
  await expect(page.locator("candidate-activity operation-progress .status")).toHaveText("succeeded");
  await expect(page.getByRole("heading", { name: "Completed files" })).toBeVisible();
  await expect(page.getByRole("cell", { name: "900", exact: true })).toBeVisible();
  await expect(page.getByRole("cell", { name: "100", exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("embedding-history.png"), fullPage: true });
  await page.getByRole("button", { name: "Search candidates", exact: true }).click();
  await page.getByRole("textbox", { name: "Index", exact: true }).fill("candidates-fsb-test");
  await page.getByRole("textbox", { name: "What expertise" }).fill("Java Spring Boot Kafka");
  await page.getByRole("button", { name: "Search candidates →", exact: true }).click();
  await expect(page.locator(".results-card tbody tr")).toHaveCount(10);
  await expect(page.getByText("Maya Chen 1", { exact: true })).toBeVisible();
  await page.locator(".results-card").getByRole("button", { name: "Details", exact: true }).first().click();
  await expect(page.getByText("Candidate profile", { exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("search-results.png"), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole("heading", { name: "Search candidates", exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("search-mobile.png"), fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole("textbox", { name: "What expertise" }).fill("simulate failure");
  await page.getByRole("button", { name: "Search candidates →", exact: true }).click();
  await expect(page.locator("operation-progress .status")).toHaveText("failed");
  await expect(page.locator("operation-progress .alert")).toContainText("Offline fixture: search request failed");
  await page.reload();
  await page.getByRole("button", { name: "Activity", exact: false }).click();
  await expect(page.getByRole("cell", { name: "Full sandbox test", exact: true }).first()).toBeVisible();
  expect(errors).toEqual([]);
});

test("stop preserves a completed fetch batch and a refreshed browser can resume it", async ({ page }) => {
  await page.goto("/");
  await page.getByRole("textbox", { name: "Dataset folder" }).fill("stop-test");
  await page.getByRole("spinbutton", { name: "Batches this run" }).fill("10");
  await page.getByRole("button", { name: "Fetch new dataset" }).click();
  await expect(page.getByRole("heading", { name: "Fetching batch 1", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Stop", exact: true }).click();
  await expect(page.locator("operation-progress .status")).toHaveText("cancelled");
  await expect(page.getByText("1,000 records across 1 files.", { exact: false })).toBeVisible();
  await page.reload();
  await page.getByRole("textbox", { name: "Dataset folder" }).fill("stop-test");
  await page.getByRole("button", { name: "Resume fetch" }).click();
  await expect(page.getByText("1,005 records across 2 files.", { exact: false })).toBeVisible();
});
